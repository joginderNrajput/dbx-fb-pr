CREATE SCHEMA IF NOT EXISTS databricks_to_fabric_premigration;

CREATE TABLE databricks_to_fabric_premigration.totals (
	scan_id SERIAL NOT NULL, 
	source TEXT, 
	mode VARCHAR(20), 
	cloud VARCHAR(20), 
	workspace_id VARCHAR(64), 
	metastore VARCHAR(255), 
	collectors TEXT, 
	discovery_workbook VARCHAR(255), 
	captured_at VARCHAR(40), 
	discovered_at VARCHAR(40), 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now(), 
	notebooks BIGINT, 
	notebook_lines BIGINT, 
	python_notebooks BIGINT, 
	sql_notebooks BIGINT, 
	scala_notebooks BIGINT, 
	r_notebooks BIGINT, 
	notebooks_not_scanned BIGINT, 
	repos BIGINT, 
	dependencies BIGINT, 
	unresolved_dependencies BIGINT, 
	jobs BIGINT, 
	job_tasks BIGINT, 
	scheduled_jobs BIGINT, 
	continuous_jobs BIGINT, 
	dlt_pipelines BIGINT, 
	clusters BIGINT, 
	gpu_clusters BIGINT, 
	clusters_with_init_scripts BIGINT, 
	instance_pools BIGINT, 
	cluster_policies BIGINT, 
	sql_warehouses BIGINT, 
	libraries BIGINT, 
	catalogs BIGINT, 
	schemas BIGINT, 
	tables BIGINT, 
	managed_tables BIGINT, 
	external_tables BIGINT, 
	views BIGINT, 
	materialized_views BIGINT, 
	streaming_tables BIGINT, 
	foreign_tables BIGINT, 
	hive_metastore_tables BIGINT, 
	columns BIGINT, 
	volumes BIGINT, 
	external_locations BIGINT, 
	storage_credentials BIGINT, 
	connections BIGINT, 
	functions BIGINT, 
	grants BIGINT, 
	sql_queries BIGINT, 
	dashboards BIGINT, 
	alerts BIGINT, 
	ml_models BIGINT, 
	serving_endpoints BIGINT, 
	experiments BIGINT, 
	secret_scopes BIGINT, 
	secrets BIGINT, 
	mounts BIGINT, 
	users BIGINT, 
	groups BIGINT, 
	service_principals BIGINT, 
	assessable_assets BIGINT, 
	compatible_assets BIGINT, 
	partial_assets BIGINT, 
	manual_assets BIGINT, 
	unsupported_assets BIGINT, 
	avg_readiness_score NUMERIC(10, 2), 
	findings BIGINT, 
	warnings BIGINT, 
	organization_id VARCHAR(128), 
	job_id VARCHAR(128), 
	PRIMARY KEY (scan_id)
);

CREATE INDEX ix_totals_org_job ON databricks_to_fabric_premigration.totals (organization_id, job_id);

CREATE TABLE databricks_to_fabric_premigration.computation (
	computation_id SERIAL NOT NULL, 
	scan_id INTEGER NOT NULL, 
	assessment_generated_at TIMESTAMP WITH TIME ZONE, 
	total_assets INTEGER, 
	total_constructs INTEGER, 
	supported_constructs NUMERIC(14, 6), 
	unsupported_constructs NUMERIC(14, 6), 
	simple_count INTEGER, 
	medium_count INTEGER, 
	complex_count INTEGER, 
	fully_automated INTEGER, 
	partially_automated INTEGER, 
	manual INTEGER, 
	manual_dev_hours NUMERIC(14, 6), 
	manual_test_hours NUMERIC(14, 6), 
	total_manual_hours NUMERIC(14, 6), 
	automation_dev_hours NUMERIC(14, 6), 
	automation_test_hours NUMERIC(14, 6), 
	total_automation_hours NUMERIC(14, 6), 
	hours_saved NUMERIC(14, 6), 
	saving_pct NUMERIC(14, 6), 
	rules_version VARCHAR(255), 
	organization_id VARCHAR(128), 
	job_id VARCHAR(128), 
	PRIMARY KEY (computation_id), 
	UNIQUE (scan_id), 
	FOREIGN KEY(scan_id) REFERENCES databricks_to_fabric_premigration.totals (scan_id)
);

CREATE INDEX ix_computation_org_job ON databricks_to_fabric_premigration.computation (organization_id, job_id);

CREATE TABLE databricks_to_fabric_premigration.inventory (
	inventory_id SERIAL NOT NULL, 
	scan_id INTEGER NOT NULL, 
	asset_key TEXT NOT NULL, 
	asset_type VARCHAR(50), 
	asset_name TEXT NOT NULL, 
	location TEXT, 
	fabric_target VARCHAR(255), 
	readiness VARCHAR(20), 
	readiness_score INTEGER, 
	findings INTEGER, 
	finding_ids TEXT, 
	lines INTEGER, 
	cells INTEGER, 
	tasks INTEGER, 
	columns INTEGER, 
	organization_id VARCHAR(128), 
	job_id VARCHAR(128), 
	PRIMARY KEY (inventory_id), 
	CONSTRAINT inventory_scan_id_asset_key_key UNIQUE (scan_id, asset_key), 
	FOREIGN KEY(scan_id) REFERENCES databricks_to_fabric_premigration.totals (scan_id)
);

CREATE INDEX ix_inventory_org_job ON databricks_to_fabric_premigration.inventory (organization_id, job_id);

CREATE TABLE databricks_to_fabric_premigration.estimation (
	estimation_id SERIAL NOT NULL, 
	scan_id INTEGER NOT NULL, 
	inventory_id INTEGER, 
	asset_name TEXT NOT NULL, 
	asset_type VARCHAR(50), 
	location TEXT, 
	total_constructs INTEGER, 
	supported NUMERIC(14, 6), 
	unsupported NUMERIC(14, 6), 
	complexity_score INTEGER, 
	complexity_level VARCHAR(20), 
	recommended_target VARCHAR(255), 
	automation_level VARCHAR(30), 
	readiness VARCHAR(20), 
	manual_dev_hours NUMERIC(14, 6), 
	manual_test_hours NUMERIC(14, 6), 
	automation_dev_hours NUMERIC(14, 6), 
	automation_test_hours NUMERIC(14, 6), 
	hours_saved NUMERIC(14, 6), 
	organization_id VARCHAR(128), 
	job_id VARCHAR(128), 
	PRIMARY KEY (estimation_id), 
	CONSTRAINT estimation_scan_id_inventory_id_key UNIQUE (scan_id, inventory_id), 
	FOREIGN KEY(scan_id) REFERENCES databricks_to_fabric_premigration.totals (scan_id), 
	FOREIGN KEY(inventory_id) REFERENCES databricks_to_fabric_premigration.inventory (inventory_id)
);

CREATE INDEX ix_estimation_org_job ON databricks_to_fabric_premigration.estimation (organization_id, job_id);

CREATE TABLE databricks_to_fabric_premigration.finding (
	finding_id SERIAL NOT NULL, 
	scan_id INTEGER NOT NULL, 
	inventory_id INTEGER, 
	asset_type VARCHAR(50), 
	rule VARCHAR(100) NOT NULL, 
	category VARCHAR(100), 
	occurrences INTEGER, 
	penalty INTEGER, 
	support VARCHAR(20), 
	guidance TEXT, 
	organization_id VARCHAR(128), 
	job_id VARCHAR(128), 
	PRIMARY KEY (finding_id), 
	FOREIGN KEY(scan_id) REFERENCES databricks_to_fabric_premigration.totals (scan_id), 
	FOREIGN KEY(inventory_id) REFERENCES databricks_to_fabric_premigration.inventory (inventory_id)
);

CREATE INDEX ix_finding_org_job ON databricks_to_fabric_premigration.finding (organization_id, job_id);
